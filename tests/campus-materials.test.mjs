test("an unknown class is a loud failure, not a silent grey box", () => {
  const lib = createMaterialLibrary(THREE);
  assert.throws(() => lib.get("marble"), /unknown material class/);
  assert.throws(() => generateTextureSet(THREE, "marble"), /unknown material class/);
  lib.dispose();
});

test("anisotropy is set, and overridable", () => {
  const a = createMaterialLibrary(THREE);
  assert.equal(a.textures("brick").map.anisotropy, 8);
  const b = createMaterialLibrary(THREE, { anisotropy: 16 });
  assert.equal(b.textures("brick").map.anisotropy, 16);
  a.dispose();
  b.dispose();
});

