// Parking Lot P101 — UCSD's all-accessible lot north of the Natural Sciences
// Building, Revelle College. Photo-sourced detail, the INVENTED class, R5.
//
// Six things decided the shape of this file, and each is a place a plausible
// build of a parking lot goes wrong:
//
//   1. THIS IS NOT A GENERIC ASPHALT LOT WITH A WHITE STALL STRIPE. Two
//      independent UCSD records and a UCSD department page all say the same
//      thing: 12 accessible + 1 reserved, "for accessible parking only".
//      Every stall in every Street View epoch is blue-bordered ADA. So the
//      paint here is BLUE — borders, aisle borders and 45 degree aisle
//      hatching — with a code-sized ISA stencil per accessible stall.
//
//   2. THE SURVEY ALREADY DREW THE INTERNAL PLAN. arcgis.ground#71 is not a
//      rectangle: its 111 deduped vertices carry the lot's outer edge, THREE
//      planted islands, the 2.0 m central walk and a 1.3 x 1.5 m utility pad.
//      Every island polygon this file draws is a CONTIGUOUS RUN of that ring
//      (section.measured.islandSlices), never a shape of its own invention.
//
//   3. STALL DEPTH IS MEASURED, STALL WIDTH IS NOT. Both rows read 5.5 m off
//      the ring — 18.04 ft against the 18 ft standard. Width has no source at
//      all: the 2026 ortho carries no periodic stripe signal at 8 px/m, so it
//      resolves the lot's plan and not its paint. Width is a banded
//      [estimated] code minimum and says so.
//
//   4. THE COUNT OF RECORD WINS OVER THE FRONTAGE. The measured frontage
//      tiled with the observed 9 + 8 + 9 module admits sixteen stalls. UCSD
//      says thirteen. Thirteen are built, and conflicts.stallCount carries
//      the gap rather than smoothing it.
//
//   5. WHAT READS AS GROUND HERE IS A LIFTED DECAL. The lot's asphalt is
//      drawn at the overlay `pad` rung, so every solid — wheel stops, sign
//      posts, the light pole, the cabinet, the hydrant, the kerbs — seats on
//      surfaceAt + overlayLift(draw.solidRung), never on bare surfaceAt, or
//      it would sink 9 cm into its own pavement. Same reason the scooter run
//      puts its obstacles on one ride plane.
//
//   6. NO TREE IS DRAWN. campus-world.js createTrees already instances both
//      of this lot's measured LiDAR trunks; a second model on the same stem
//      is exactly what that module's skipKeys mechanism exists to prevent.
//      section.measured.trees carries both rows and counts.trees is a
//      declared zero.
//
// There is no text mechanism in this repo, so NO PARKING, PARKING ONLY,
// MINIMUM FINE $450 and NO PARKING FIRE LANE are recorded in section.legends
// and rendered nowhere. The ISA is a SYMBOL, not text, and is drawn.
//
// No dimension and no colour lives in this file: every metre comes from
// `derivations.figures` (with arithmetic), `estimates` (banded, naming the
// pattern extended), `reads` (pinned citations) or `draw` (declared render
// constants); every hex from `section.colors` through a guard that throws.
// Textures are code-generated by campus-materials.js. Deterministic — no
// randomness, no clock, no loader.
