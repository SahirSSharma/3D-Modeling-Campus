/**
 * Build Lot P101's photo-sourced detail. `photo` is the loaded photo-detail
 * document; this reads only its `p101` key and writes nothing back.
 * Everything seats on `surfaceAt` — the height of the DRAWN terrain triangle —
 * lifted onto the campus-overlay.js ladder, never on `heightAt` and never on
 * a local constant.
 */
export function createPhotoP101(scene, { photo, heightAt, surfaceAt } = {}) {
  const group = new THREE.Group();
  group.name = "photo-p101";
  const section = photo?.p101;
  if (!section) {
    scene?.add(group);
    return { group, counts: {} };
  }
  const ground = surfaceAt || heightAt;
  if (typeof ground !== "function") {
    throw new Error("campus-photo-p101: needs surfaceAt (or heightAt) to place on the ground");
  }

  /* PRE-MERGE GUARD. A document that predates the R5 merge of
     Revelle-College-Sources/merge/r5/p101.json has none of the blocks below,
     and half a striped lot drawn off a half-section is the silent failure
     this repo keeps failing on. Build NOTHING and say which keys are
     missing, so the merge cannot half-land unnoticed. */
  const missing = [
    "measured", "colors", "derivations", "estimates", "reads", "draw",
    "plan", "stalls", "paint", "furniture", "planting", "counts",
  ].filter((k) => !section[k]);
  if (section.measured && !section.measured.islandSlices) missing.push("measured.islandSlices");
  if (section.measured && !section.measured.ring) missing.push("measured.ring");
  if (section.stalls && !section.stalls.layout) missing.push("stalls.layout");
  if (section.plan && !section.plan.segments) missing.push("plan.segments");
  if (missing.length) {
    scene?.add(group);
    return { group, counts: { pendingMerge: missing.join(",") } };
  }

  const { colors, draw: D, plan: P, stalls: ST, paint: PT, furniture: FU, planting: PL } = section;
  /* Every colour goes through here; an undeclared role would silently become
     opaque white in campus-materials.js and must throw instead. */
  const hue = (role) => {
    const v = colors[role];
    if (typeof v !== "string") {
      throw new Error(`campus-photo-p101: no colour declared for role "${role}" — `
        + "an unset role silently becomes white in campus-materials.js and must never reach a material");
    }
    return v;
  };
  const T = D.tiles;
  const GL = D.glyph;

  /* THE LOT'S OWN DATUM. What reads as ground inside this lot is the pad-rung
     asphalt decal, so every solid stands on that plane and not on the bare
     terrain 9 cm below it. */
  const padLift = overlayLift(D.surfaceRung);
  const carpetLift = overlayLift(D.walkRung);
  const paintLift = overlayLift(D.paintRung);
  const solidLift = overlayLift(D.solidRung);
  /**
   * A solid seats on the HIGHEST drawn ground under its own footprint, not on
   * the ground under its centre: a rigid box or cylinder placed at a centre
   * sample dips into the hill on its uphill side, and a wheel stop half
   * buried in its own pavement is the failure this repo keeps failing on.
   * The mayer builder makes the same choice for the same reason.
   */
  const seat = (x, z, radius = 0) => {
    let hi = -Infinity;
    const n = radius > 0 ? D.footprintSamples : 0;
    for (let i = 0; i <= n; i++) {
      const px = i === 0 ? x : x + Math.cos((2 * Math.PI * (i - 1)) / n) * radius;
      const pz = i === 0 ? z : z + Math.sin((2 * Math.PI * (i - 1)) / n) * radius;
      const g = ground(px, pz);
      if (!Number.isFinite(g)) {
        throw new Error(`campus-photo-p101: surfaceAt returned ${g} under a solid at (${px}, ${pz})`);
      }
      if (g > hi) hi = g;
    }
    return hi + solidLift;
  };

  const bin = () => ({ pos: [], uv: [], runs: 0 });
  const bins = {
    asphalt: bin(), walk: bin(), walkSkirt: bin(), pad: bin(), mulch: bin(),
    groundcover: bin(), groundcoverSkirt: bin(), kerbFace: bin(), kerbCap: bin(),
    blue: bin(), isaOutline: bin(), isaField: bin(), isaGlyph: bin(),
  };
  const counts = {
    asphaltFills: 0, islands: 0, islandKerbs: 0, islandPlantings: 0,
    walkSlabs: 0, utilityPads: 0,
    stalls: 0, accessibleStalls: 0, reservedStalls: 0, pairs: 0, accessAisles: 0,
    stallLines: 0, aisleHeadLines: 0, hatchStripes: 0, isaStencils: 0, isaGlyphParts: 0,
    wheelStops: 0, signs: 0, signPosts: 0, vanPlates: 0,
    lightPoles: 0, cabinets: 0, hydrants: 0, manholes: 0,
    fireLaneKerbs: 0, mulchBeds: 0, hedgeShrubs: 0,
    /* DECLARED ZEROES — deliberate absences, each with its reason in
       section.counts.zeroesWhy. campus-world.js draws this lot's two measured
       trunks; there is no text mechanism; and no source shows a pay station,
       a white stall or a second entrance. */
    trees: 0, legends: 0, payStations: 0, meters: 0, permitDispensers: 0,
    whiteStalls: 0, numberedStalls: 0, compactStalls: 0, secondEntrances: 0,
  };

  /* ------------------------------------------------------- the paved fill */
  const ring = dedupe(section.measured.ring, D.dedupeTol);
  drape(ring, ground, padLift, D.drapeSeg, D.drapeMaxDepth, bins.asphalt);
  counts.asphaltFills++;

  /* -------------------------------------------- islands, kerbed + planted */
  /* Each island is a CONTIGUOUS RUN of the survey ring, closed on the chord
     between its own two endpoints. Nothing about their shape is invented;
     measured.islandSlices records which run, and which closures are surveyed
     edges and which (the west island's base) is not. */
  const IS = section.measured.islandSlices;
  const kerbW = PL.islandKerb.width;
  const kerbH = PL.islandKerb.height;
  for (const key of IS.polygons) {
    const [i0, i1] = IS[key].range;
    const poly = ring.slice(i0, i1 + 1);
    const out = ringArea(poly) > 0;
    skirt(poly.concat([poly[0]]), ground, padLift, padLift + kerbH, T.kerb, T.kerb, bins.kerbFace, out);
    const inner = insetRing(poly, kerbW);
    skirt(inner.concat([inner[0]]), ground, padLift + kerbH, padLift + PL.groundcover.height,
      T.groundcover, T.groundcover, bins.groundcoverSkirt, ringArea(inner) > 0);
    /* The kerb cap: the flat top between the outer line and the inset line. */
    for (let i = 0; i < poly.length; i++) {
      const j = (i + 1) % poly.length;
      flatPoly([poly[i], poly[j], inner[j], inner[i]], ground, padLift + kerbH, bins.kerbCap);
    }
    drape(inner, ground, padLift + PL.groundcover.height, D.drapeSeg, D.drapeMaxDepth, bins.groundcover);
    counts.islandKerbs++;
    counts.islandPlantings++;
  }
  /* Three islands, four polygons: the east island is SPLIT by the central
     walk into two lobes and the survey draws each lobe separately. */
  counts.islands = IS.islands.length;

  /* -------------------------------------------------- the central walk */
  const walkTop = carpetLift + P.walk.thickness;
  for (const [x0, x1] of [[P.walk.x0a, P.walk.x1a], [P.walk.x0b, P.walk.x1b]]) {
    drape(rect(x0, ST.rowN.z1, x1, ST.rowS.z0), ground, walkTop,
      D.drapeSeg, D.drapeMaxDepth, bins.walk);
    /* Two edges, each looking away from the walk: the north edge north, the
       south edge south. The run is walked west to east in both cases. */
    for (const [z, flip] of [[ST.rowN.z1, true], [ST.rowS.z0, false]]) {
      const line = [];
      const n = Math.max(1, Math.ceil((x1 - x0) / D.kerbSegment));
      for (let i = 0; i <= n; i++) line.push([x0 + ((x1 - x0) * i) / n, z]);
      skirt(line, ground, padLift, walkTop, T.concrete, T.concrete, bins.walkSkirt, flip);
    }
    counts.walkSlabs++;
  }

  /* --------------------------------------------------- the utility pad */
  {
    const [i0, i1] = IS.pad.range;
    const poly = ring.slice(i0, i1 + 1);
    drape(poly, ground, carpetLift, D.drapeSeg, D.drapeMaxDepth, bins.pad);
    counts.utilityPads++;
  }

  /* ---------------------------------------- the NatSci frontage planter */
  drape(rect(FU.fireLaneKerb.x0, P.bands.aisleS.z1, FU.fireLaneKerb.x1,
    P.bands.aisleS.z1 + P.bands.planter.depth), ground, padLift,
    D.drapeSeg, D.drapeMaxDepth, bins.mulch);
  counts.mulchBeds++;

  /* ----------------------------------------------- the stations, derived */
  /* One pass produces every stall, every access aisle and every wheel-stop,
     sign and stencil position, from the section's own placement rule: a
     segment's spare frontage divided equally into (pairs + 1) gaps. */
  const stalls = [];
  const aisles = [];
  const rowOf = (row) => (row === "N" ? ST.rowN : ST.rowS);
  /* The HEAD is the central-walk end in both rows — cars nose south in Row N
     and north in Row S, which is why one line of signs serves both. */
  const headZ = (row) => (row === "N" ? ST.rowN.z1 : ST.rowS.z0);
  const openZ = (row) => (row === "N" ? ST.rowN.z0 : ST.rowS.z1);
  const at = (path) => path.split(".").reduce((o, k) => (o == null ? o : o[k]), section);

  for (const entry of ST.layout.pairs) {
    const seg = P.segments[entry.segment];
    const n = at(entry.count);
    const pad = at(entry.pad);
    const isVan = ST.layout.vanPairOrder.includes(entry.segment);
    for (let i = 0; i < n; i++) {
      const x0 = seg.x0 + pad * (i + 1) + ST.pairModule * i;
      const a0 = x0 + ST.width;
      const a1 = a0 + ST.vanAisle;
      stalls.push({ x0, x1: a0, row: seg.row, accessible: true, van: isVan && i === 0 });
      stalls.push({ x0: a1, x1: x0 + ST.pairModule, row: seg.row, accessible: true, van: false });
      aisles.push({ x0: a0, x1: a1, row: seg.row });
      counts.pairs++;
      counts.accessAisles++;
    }
  }
  {
    const res = ST.layout.reserved;
    const seg = P.segments[res.segment];
    const n = at(res.count);
    const pad = at(res.pad);
    for (let i = 0; i < n; i++) {
      const x0 = seg.x0 + pad * (i + 1) + ST.width * i;
      stalls.push({ x0, x1: x0 + ST.width, row: seg.row, accessible: false, van: false });
    }
  }
  for (const s of stalls) {
    counts.stalls++;
    if (s.accessible) counts.accessibleStalls++; else counts.reservedStalls++;
  }

  /* ------------------------------------------------------------- the paint */
  const lw = PT.lineWidth;
  /* Belt-and-braces only. campus-overlay.js sets depthWrite:false on the
     paint rung, so these millimetres cannot order overlapping sub-layers —
     that is renderOrder, below. Same contract as the overlay header. */
  const stack = (k) => paintLift + D.paintStack * k;
  for (const s of stalls) {
    const hz = headZ(s.row);
    const oz = openZ(s.row);
    const zLo = Math.min(hz, oz);
    const zHi = Math.max(hz, oz);
    /* Two flanks and a head. The open (drive-aisle) end carries no line. */
    for (const x of [s.x0, s.x1]) {
      flatPoly(rect(x - lw / 2, zLo, x + lw / 2, zHi), ground, stack(0), bins.blue);
      counts.stallLines++;
    }
    /* The head line is laid INSIDE the stall, not straddling its edge: the
       survey's own head run wobbles ring.headWobble along its length, and a
       straddling line is the half that falls outside it. */
    const hIn = s.row === "N" ? hz - lw : hz;
    flatPoly(rect(s.x0 - lw / 2, hIn, s.x1 + lw / 2, hIn + lw), ground, stack(0), bins.blue);
    counts.stallLines++;
  }
  for (const a of aisles) {
    const hz = headZ(a.row);
    const oz = openZ(a.row);
    const zLo = Math.min(hz, oz);
    const zHi = Math.max(hz, oz);
    const hIn = a.row === "N" ? hz - lw : hz;
    flatPoly(rect(a.x0 - lw / 2, hIn, a.x1 + lw / 2, hIn + lw), ground, stack(0), bins.blue);
    counts.aisleHeadLines++;
    /* 45 degree hatching, laid from the aisle's own low corner at half a
       pitch and then every pitch, each stripe CLIPPED to the aisle so no
       paint escapes onto a stall or a drive aisle. */
    const c = Math.SQRT1_2;
    const box = rect(a.x0, zLo, a.x1, zHi);
    const proj = (p) => p[0] * c - p[1] * c;
    let pmin = Infinity;
    for (const p of box) pmin = Math.min(pmin, proj(p));
    for (let k = 0; k < PT.hatchPerAisle; k++) {
      const t = pmin + PT.hatchPitch * (k + 0.5);
      let poly = clipHalf(box, c, -c, t + PT.hatchWidth / 2);
      poly = clipHalf(poly, -c, c, -(t - PT.hatchWidth / 2));
      if (poly.length >= 3) {
        flatPoly(poly, ground, stack(1), bins.blue);
        counts.hatchStripes++;
      }
    }
  }

  /* THE ISA STENCIL — a symbol, not text, so it may be drawn. A white square
     at the code's 36 in, a blue field inside it, and a four-part white glyph
     whose proportions are declared in draw.glyph as fractions of that field.
     The three sub-layers go into THREE bins, not the shared white/blue paint
     meshes: those two shared a paint-rung renderOrder, depthWrite is off, and
     the white square ate the blue field (campus-overlay.js "white blotches
     on the courts"). Eighth courts and campus-markings.js order overlapping
     paint by distinct renderOrder; the ISA stack does the same inside the
     paint rung at assembly. */
  for (const s of stalls) {
    if (!s.accessible) continue;
    const cx = (s.x0 + s.x1) / 2;
    const oz = openZ(s.row);
    const cz = s.row === "N" ? oz + PT.isaInset : oz - PT.isaInset;
    const h = ST.isaSize / 2;
    flatPoly(rect(cx - h, cz - h, cx + h, cz + h), ground, stack(2), bins.isaOutline);
    const f = PT.isaField / 2;
    flatPoly(rect(cx - f, cz - f, cx + f, cz + f), ground, stack(3), bins.isaField);
    const F = PT.isaField;
    /* wheel: an annulus, drawn as a fan of quads */
    const ro = GL.wheelOuter * F;
    const ri = GL.wheelInner * F;
    const wx = cx + GL.wheelOffsetX * F;
    const wz = cz + GL.wheelOffsetZ * F;
    for (let i = 0; i < D.glyphSegments; i++) {
      const a0 = (i / D.glyphSegments) * Math.PI * 2;
      const a1 = ((i + 1) / D.glyphSegments) * Math.PI * 2;
      flatPoly([
        [wx + Math.cos(a0) * ri, wz + Math.sin(a0) * ri],
        [wx + Math.cos(a0) * ro, wz + Math.sin(a0) * ro],
        [wx + Math.cos(a1) * ro, wz + Math.sin(a1) * ro],
        [wx + Math.cos(a1) * ri, wz + Math.sin(a1) * ri],
      ], ground, stack(4), bins.isaGlyph);
    }
    counts.isaGlyphParts++;
    /* head: a disc */
    const hr = GL.headRadius * F;
    const hx = cx + GL.headOffsetX * F;
    const hz2 = cz + GL.headOffsetZ * F;
    const disc = [];
    for (let i = 0; i < D.glyphSegments; i++) {
      const a0 = (i / D.glyphSegments) * Math.PI * 2;
      disc.push([hx + Math.cos(a0) * hr, hz2 + Math.sin(a0) * hr]);
    }
    flatPoly(disc, ground, stack(4), bins.isaGlyph);
    counts.isaGlyphParts++;
    /* back and leg: two rotated bars */
    for (const [ox, oz2, len, wid, ang] of [
      [GL.backOffsetX, GL.backOffsetZ, GL.backLength, GL.barWidth, GL.backAngle],
      [GL.legOffsetX, GL.legOffsetZ, GL.legLength, GL.barWidth, GL.legAngle],
    ]) {
      const bx = cx + ox * F;
      const bz = cz + oz2 * F;
      const dx = Math.cos(ang) * len * F / 2;
      const dz = Math.sin(ang) * len * F / 2;
      const nx = -Math.sin(ang) * wid * F / 2;
      const nz = Math.cos(ang) * wid * F / 2;
      flatPoly([
        [bx - dx - nx, bz - dz - nz], [bx + dx - nx, bz + dz - nz],
        [bx + dx + nx, bz + dz + nz], [bx - dx + nx, bz - dz + nz],
      ], ground, stack(4), bins.isaGlyph);
      counts.isaGlyphParts++;
    }
    counts.isaStencils++;
  }

  /* -------------------------------------------------------- the fire lane */
  {
    const k = FU.fireLaneKerb;
    const n = Math.max(1, Math.ceil(k.run / D.kerbSegment));
    const line = [];
    for (let i = 0; i <= n; i++) line.push([k.x0 + (k.run * i) / n, P.bands.aisleS.z1]);
    /* The painted face looks NORTH, into the aisle it forbids parking in. */
    skirt(line, ground, solidLift, solidLift + k.height, T.kerb, T.kerb, bins.kerbFace, true);
    for (let i = 0; i < n; i++) {
      flatPoly([
        [line[i][0], line[i][1]], [line[i + 1][0], line[i + 1][1]],
        [line[i + 1][0], line[i + 1][1] + k.width], [line[i][0], line[i][1] + k.width],
      ], ground, solidLift + k.height, bins.kerbCap);
    }
    counts.fireLaneKerbs++;
  }

  /* ------------------------------------------------------------ assembly */
  const surfaces = new THREE.Group();
  surfaces.name = "p101-surfaces";
  const decal = (cls, color, rung, repeat) => {
    const mat = applyOverlayDepth(lib().get(cls, { color, repeat }), rung);
    return mat;
  };
  for (const [key, cls, role, rung, tile, meshName] of [
    ["asphalt", "asphalt", "asphalt", D.surfaceRung, T.asphalt, "p101-asphalt-sourced"],
    ["mulch", "lavaRock", "mulchBark", D.mulchRung, T.mulch, "p101-planter-mulch-estimated"],
    ["walk", "pavingConcreteUnit", "concrete", D.walkRung, T.concrete, "p101-walk-estimated"],
    ["pad", "pavingConcreteUnit", "concrete", D.walkRung, T.concrete, "p101-utility-pad-measured"],
    ["groundcover", "foliage", "groundcoverGreen", D.plantingRung, T.groundcover, "p101-island-groundcover-estimated"],
    ["blue", "smoothConcrete", "paintBlue", D.paintRung, T.paint, "p101-paint-blue-sourced"],
  ]) {
    if (!bins[key].runs) continue;
    const mesh = new THREE.Mesh(bake(bins[key]), decal(cls, hue(role), rung, 1 / tile));
    mesh.renderOrder = OVERLAY[rung].renderOrder;
    mesh.receiveShadow = true;
    mesh.name = meshName;
    surfaces.add(mesh);
  }
  /* ISA sub-layers: outline → field → glyph. Same paint-rung depth state
     (polygonOffset, depthWrite:false) as the stall lines; distinct
     ascending renderOrder so the order does not depend on the 2 mm lift.
     Eighth courts / campus-markings.js: overlapping paint families each
     get their own renderOrder. The ladder only has paint then logo, so
     the three steps stay inside the paint rung as paint, paint+1, paint+2. */
  const paintOrder = OVERLAY[D.paintRung].renderOrder;
  for (const [key, role, step, meshName] of [
    ["isaOutline", "paintWhite", 0, "p101-paint-isa-outline-estimated"],
    ["isaField", "paintBlue", 1, "p101-paint-isa-field-sourced"],
    ["isaGlyph", "paintWhite", 2, "p101-paint-isa-glyph-estimated"],
  ]) {
    if (!bins[key].runs) continue;
    const mesh = new THREE.Mesh(bake(bins[key]), decal("smoothConcrete", hue(role), D.paintRung, 1 / T.paint));
    mesh.renderOrder = paintOrder + step;
    mesh.receiveShadow = true;
    mesh.name = meshName;
    surfaces.add(mesh);
  }
  group.add(surfaces);

  const solids = new THREE.Group();
  solids.name = "p101-solids";
  for (const [key, cls, role, tile, meshName] of [
    ["kerbFace", "smoothConcrete", "fireLaneRed", T.kerb, "p101-kerb-face-sourced"],
    ["kerbCap", "smoothConcrete", "kerbConcrete", T.kerb, "p101-kerb-cap-estimated"],
    ["walkSkirt", "pavingConcreteUnit", "concrete", T.concrete, "p101-walk-edge-estimated"],
    ["groundcoverSkirt", "foliage", "groundcoverGreen", T.groundcover, "p101-island-planting-edge-estimated"],
  ]) {
    if (!bins[key].runs) continue;
    const mesh = new THREE.Mesh(bake(bins[key]), lib().get(cls, { color: hue(role), repeat: 1 / tile }));
    mesh.castShadow = mesh.receiveShadow = true;
    mesh.name = meshName;
    solids.add(mesh);
  }

  /* -------------------------------------------------------- wheel stops */
  {
    const w = FU.wheelStop;
    const geo = new THREE.BoxGeometry(w.length, w.height, w.width);
    const mesh = new THREE.InstancedMesh(geo, lib().get("smoothConcrete",
      { color: hue("wheelStopYellow"), repeat: 1 / T.kerb }), stalls.length);
    mesh.name = "p101-wheelstop-sourced";
    mesh.castShadow = mesh.receiveShadow = true;
    const m = new THREE.Matrix4();
    stalls.forEach((s, i) => {
      const cx = (s.x0 + s.x1) / 2;
      const cz = s.row === "N" ? w.rowNz : w.rowSz;
      m.makeTranslation(cx, seat(cx, cz, Math.hypot(w.length, w.width) / 2) + w.height / 2, cz);
      mesh.setMatrixAt(i, m);
      counts.wheelStops++;
    });
    mesh.instanceMatrix.needsUpdate = true;
    solids.add(mesh);
  }

  /* ------------------------------------------------------------- signage */
  {
    const S = FU.sign;
    const postGeo = new THREE.BoxGeometry(S.postSize, S.topHeight, S.postSize);
    const posts = new THREE.InstancedMesh(postGeo, lib().get("metalPanel",
      { color: hue("postGalvanised"), repeat: 1 / T.metal }), stalls.length);
    posts.name = "p101-sign-post-estimated";
    posts.castShadow = posts.receiveShadow = true;
    const faceGeo = new THREE.BoxGeometry(S.faceWidth, S.faceHeight, D.signThickness);
    const faces = new THREE.InstancedMesh(faceGeo, lib().get("metalPanel",
      { color: hue("signBlue"), repeat: 1 / T.metal }), stalls.length);
    faces.name = "p101-sign-face-estimated";
    faces.castShadow = faces.receiveShadow = true;
    const vanGeo = new THREE.BoxGeometry(S.faceWidth, S.plateHeight, D.signThickness);
    const vanCount = stalls.filter((s) => s.van).length;
    const plates = new THREE.InstancedMesh(vanGeo, lib().get("metalPanel",
      { color: hue("signWhite"), repeat: 1 / T.metal }), Math.max(1, vanCount));
    plates.name = "p101-sign-vanplate-estimated";
    plates.castShadow = plates.receiveShadow = true;
    plates.count = vanCount;

    const m = new THREE.Matrix4();
    let v = 0;
    stalls.forEach((s, i) => {
      const cx = (s.x0 + s.x1) / 2;
      /* Both rows' signs stand ON the central walk, which is why they form a
         single line: the head of Row N and the head of Row S face each other
         across it. The post therefore seats on the walk's own top surface. */
      const cz = s.row === "N"
        ? ST.rowN.z1 + S.postSize / 2
        : ST.rowS.z0 - S.postSize / 2;
      const base = seat(cx, cz, Math.hypot(S.postSize, S.postSize) / 2) + P.walk.thickness;
      m.makeTranslation(cx, base + S.topHeight / 2, cz);
      posts.setMatrixAt(i, m);
      counts.signPosts++;
      m.makeTranslation(cx, base + S.faceBottom + S.faceHeight / 2, cz);
      faces.setMatrixAt(i, m);
      counts.signs++;
      if (s.van) {
        m.makeTranslation(cx, base + S.faceBottom - S.plateHeight / 2, cz);
        plates.setMatrixAt(v++, m);
        counts.vanPlates++;
      }
    });
    posts.instanceMatrix.needsUpdate = true;
    faces.instanceMatrix.needsUpdate = true;
    plates.instanceMatrix.needsUpdate = true;
    solids.add(posts);
    solids.add(faces);
    if (vanCount) solids.add(plates);
  }

  /* ---------------------------------------------------------- light pole */
  {
    const L = FU.pole;
    const y0 = seat(L.x, L.z, L.baseRadius);
    const baseMesh = new THREE.Mesh(
      new THREE.CylinderGeometry(L.baseRadius, L.baseRadius, L.baseHeight, D.poleSegments),
      lib().get("smoothConcrete", { color: hue("concrete"), repeat: 1 / T.concrete }));
    baseMesh.position.set(L.x, y0 + L.baseHeight / 2, L.z);
    baseMesh.name = "p101-pole-base-estimated";
    const shaftH = L.height - L.baseHeight;
    const shaft = new THREE.Mesh(
      new THREE.CylinderGeometry(L.topRadius, L.buttRadius, shaftH, D.poleSegments),
      lib().get("metalPanel", { color: hue("poleDark"), repeat: 1 / T.metal }));
    shaft.position.set(L.x, y0 + L.baseHeight + shaftH / 2, L.z);
    shaft.name = "p101-pole-shaft-estimated";
    const arm = new THREE.Mesh(
      new THREE.BoxGeometry(L.armLength, L.topRadius * 2, L.topRadius * 2),
      lib().get("metalPanel", { color: hue("poleDark"), repeat: 1 / T.metal }));
    arm.position.set(L.x + L.armLength / 2, y0 + L.height - L.headDepth / 2, L.z);
    arm.name = "p101-pole-arm-estimated";
    const head = new THREE.Mesh(
      new THREE.BoxGeometry(L.headLength, L.headDepth, L.headWidth),
      lib().get("metalPanel", { color: hue("poleDark"), repeat: 1 / T.metal }));
    head.position.set(L.x + L.armLength, y0 + L.height - L.headDepth / 2, L.z);
    head.name = "p101-pole-head-estimated";
    for (const p of [baseMesh, shaft, arm, head]) {
      p.castShadow = p.receiveShadow = true;
      solids.add(p);
    }
    counts.lightPoles++;
  }

  /* ------------------------------------------------- the point items */
  {
    const C = FU.cabinet;
    const cab = new THREE.Mesh(
      new THREE.BoxGeometry(C.width, C.height, C.depth),
      lib().get("metalPanel", { color: hue("cabinetGrey"), repeat: 1 / T.metal }));
    cab.position.set(P.pad.cx, seat(P.pad.cx, P.pad.cz, Math.hypot(C.width, C.depth) / 2) + C.height / 2, P.pad.cz);
    cab.name = "p101-utility-cabinet-sourced";
    cab.castShadow = cab.receiveShadow = true;
    solids.add(cab);
    counts.cabinets++;
  }
  {
    const H = FU.hydrant;
    const y0 = seat(H.x, H.z, H.radius);
    const mat = lib().get("metalPanel", { color: hue("hydrantYellow"), repeat: 1 / T.metal });
    const barrel = new THREE.Mesh(
      new THREE.CylinderGeometry(H.radius, H.radius, H.height, D.hydrantSegments), mat);
    barrel.position.set(H.x, y0 + H.height / 2, H.z);
    barrel.name = "p101-hydrant-barrel-sourced";
    const bonnet = new THREE.Mesh(
      new THREE.SphereGeometry(H.radius, D.hydrantSegments, D.hydrantSegments), mat);
    bonnet.position.set(H.x, y0 + H.height, H.z);
    bonnet.name = "p101-hydrant-bonnet-sourced";
    for (const p of [barrel, bonnet]) { p.castShadow = p.receiveShadow = true; solids.add(p); }
    counts.hydrants++;
  }
  {
    const M = FU.manhole;
    const cover = new THREE.Mesh(
      new THREE.CylinderGeometry(M.radius, M.radius, D.manholeThickness, D.manholeSegments),
      lib().get("metalPanel", { color: hue("manholeIron"), repeat: 1 / T.metal }));
    cover.position.set(M.x, seat(M.x, M.z, M.radius) + D.manholeThickness / 2, M.z);
    cover.name = "p101-manhole-sourced";
    cover.receiveShadow = true;
    solids.add(cover);
    counts.manholes++;
  }

  /* ------------------------------------------------- the NatSci hedge */
  {
    const H = PL.hedge;
    const geo = new THREE.SphereGeometry(H.radius, D.hedgeSegments, D.hedgeSegments);
    const mesh = new THREE.InstancedMesh(geo,
      lib().get("foliage", { color: hue("hedgeGreen"), repeat: 1 / T.groundcover }), H.count);
    mesh.name = "p101-natsci-hedge-sourced";
    mesh.castShadow = mesh.receiveShadow = true;
    const m = new THREE.Matrix4();
    const scale = new THREE.Vector3(1, H.height / 2 / H.radius, 1);
    const q = new THREE.Quaternion();
    const pos = new THREE.Vector3();
    for (let i = 0; i < H.count; i++) {
      const x = FU.fireLaneKerb.x0 + H.pitch * (i + 0.5);
      pos.set(x, seat(x, H.z, H.radius) + H.height / 2, H.z);
      m.compose(pos, q, scale);
      mesh.setMatrixAt(i, m);
      counts.hedgeShrubs++;
    }
    mesh.instanceMatrix.needsUpdate = true;
    solids.add(mesh);
  }

  group.add(solids);
  scene?.add(group);
  return { group, counts };
}
