/* ------------------------------------------------------------- ring tools */

/** Collapse consecutive duplicate vertices at the survey's own tolerance. */
function dedupe(ring, tol) {
  const out = [ring[0]];
  for (const p of ring.slice(1)) {
    const q = out[out.length - 1];
    if (Math.abs(p[0] - q[0]) > tol || Math.abs(p[1] - q[1]) > tol) out.push(p);
  }
  return out;
}

/** Signed area of a closed ring in (x, z); positive is counter-clockwise. */
function ringArea(ring) {
  let a = 0;
  for (let i = 0; i < ring.length; i++) {
    const j = (i + 1) % ring.length;
    a += ring[i][0] * ring[j][1] - ring[j][0] * ring[i][1];
  }
  return a / 2;
}

/**
 * A SURVEYED GROUND POLYGON, DRAPED — the same ShapeUtils triangulation and
 * the same y-negation campus-world.js uses over the identical polygon, split
 * until no edge exceeds `seg` so the carpet follows the drawn terrain rather
 * than spanning it.
 */
function drape(poly, ground, lift, seg, maxDepth, out) {
  const contour = poly.map(([x, z]) => new THREE.Vector2(x, -z));
  if (contour.length < 3) return;
  let faces;
  try {
    faces = THREE.ShapeUtils.triangulateShape(contour, []);
  } catch {
    return;
  }
  const emit = (a, b, c) => {
    for (const p of [a, b, c]) {
      const g = ground(p.x, p.y);
      if (!Number.isFinite(g)) {
        throw new Error(`campus-photo-p101: surfaceAt returned ${g} inside a surveyed ground polygon at (${p.x}, ${p.y})`);
      }
      out.pos.push(p.x, g + lift, p.y);
      out.uv.push(p.x, p.y);
    }
    out.runs++;
  };
  const split = (a, b, c, depth) => {
    const longest = Math.max(a.distanceTo(b), b.distanceTo(c), c.distanceTo(a));
    if (depth >= maxDepth || longest <= seg) { emit(a, b, c); return; }
    const ab = a.clone().add(b).multiplyScalar(0.5);
    const bc = b.clone().add(c).multiplyScalar(0.5);
    const ca = c.clone().add(a).multiplyScalar(0.5);
    split(a, ab, ca, depth + 1);
    split(ab, b, bc, depth + 1);
    split(ca, bc, c, depth + 1);
    split(ab, bc, ca, depth + 1);
  };
  for (const [i, j, k] of faces) {
    split(
      new THREE.Vector2(contour[i].x, -contour[i].y),
      new THREE.Vector2(contour[j].x, -contour[j].y),
      new THREE.Vector2(contour[k].x, -contour[k].y),
      0,
    );
  }
}

/**
 * A flat convex polygon at one lift over the drawn ground, fan-triangulated.
 * Wound so the face always looks UP: a negative shoelace in (x, z) is the
 * up-facing sense campus-world.js's own y-negated triangulation produces, so
 * a clipped hatch stripe or a kerb cap can be handed over in either order.
 */
function flatPoly(pts, ground, lift, out) {
  if (pts.length < 3) return;
  let a2 = 0;
  for (let i = 0; i < pts.length; i++) {
    const j = (i + 1) % pts.length;
    a2 += pts[i][0] * pts[j][1] - pts[j][0] * pts[i][1];
  }
  const poly = a2 > 0 ? pts.slice().reverse() : pts;
  const y = (p) => {
    const g = ground(p[0], p[1]);
    if (!Number.isFinite(g)) {
      throw new Error(`campus-photo-p101: surfaceAt returned ${g} under a painted polygon at (${p[0]}, ${p[1]})`);
    }
    return g + lift;
  };
  for (let i = 1; i < poly.length - 1; i++) {
    for (const p of [poly[0], poly[i], poly[i + 1]]) {
      out.pos.push(p[0], y(p), p[1]);
      out.uv.push(p[0], p[1]);
    }
    out.runs++;
  }
}

/** An axis-aligned painted rectangle, as a polygon. */
const rect = (x0, z0, x1, z1) => [[x0, z0], [x1, z0], [x1, z1], [x0, z1]];

/** Sutherland-Hodgman clip of a convex polygon by the half-plane n.p <= d. */
function clipHalf(poly, nx, nz, d) {
  const out = [];
  for (let i = 0; i < poly.length; i++) {
    const a = poly[i];
    const b = poly[(i + 1) % poly.length];
    const da = nx * a[0] + nz * a[1] - d;
    const db = nx * b[0] + nz * b[1] - d;
    if (da <= 0) out.push(a);
    if ((da <= 0) !== (db <= 0)) {
      const t = da / (da - db);
      out.push([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t]);
    }
  }
  return out;
}

/**
 * A vertical band standing on the drawn ground along an open polyline.
 * `flip` reverses the quad winding: the base order faces (-dz, 0, dx) along
 * the run, and a kerb has to look OUTWARD off its own ring or the lit side
 * of every island is the side nobody can see.
 */
function skirt(line, ground, y0Lift, y1Lift, tileU, tileV, out, flip) {
  for (let i = 0; i < line.length - 1; i++) {
    const [ax, az] = line[i];
    const [bx, bz] = line[i + 1];
    const ga = ground(ax, az);
    const gb = ground(bx, bz);
    if (!Number.isFinite(ga) || !Number.isFinite(gb)) {
      throw new Error("campus-photo-p101: surfaceAt returned nothing finite under a kerb band");
    }
    const u = Math.hypot(bx - ax, bz - az) / tileU;
    const v = (y1Lift - y0Lift) / tileV;
    const q = flip
      ? [
        [ax, ga + y0Lift, az, 0, 0], [bx, gb + y1Lift, bz, u, v], [bx, gb + y0Lift, bz, u, 0],
        [ax, ga + y0Lift, az, 0, 0], [ax, ga + y1Lift, az, 0, v], [bx, gb + y1Lift, bz, u, v],
      ]
      : [
        [ax, ga + y0Lift, az, 0, 0], [bx, gb + y0Lift, bz, u, 0], [bx, gb + y1Lift, bz, u, v],
        [ax, ga + y0Lift, az, 0, 0], [bx, gb + y1Lift, bz, u, v], [ax, ga + y1Lift, az, 0, v],
      ];
    for (const [x, y, z, uu, vv] of q) { out.pos.push(x, y, z); out.uv.push(uu, vv); }
    out.runs++;
  }
}

/** Offset a closed ring inward (toward its interior) by `w`, per-vertex. */
function insetRing(ring, w) {
  const ccw = ringArea(ring) > 0;
  const s = ccw ? -1 : 1;
  const n = ring.length;
  return ring.map((p, i) => {
    const a = ring[(i + n - 1) % n];
    const b = ring[(i + 1) % n];
    const d0 = Math.hypot(p[0] - a[0], p[1] - a[1]) || 1;
    const d1 = Math.hypot(b[0] - p[0], b[1] - p[1]) || 1;
    const nx = (s * ((p[1] - a[1]) / d0 + (b[1] - p[1]) / d1)) / 2;
    const nz = (-s * ((p[0] - a[0]) / d0 + (b[0] - p[0]) / d1)) / 2;
    const l = Math.hypot(nx, nz) || 1;
    return [p[0] + (nx / l) * w, p[1] + (nz / l) * w];
  });
}

/** Fold a bin into one geometry. */
function bake(bin) {
  const geo = new THREE.BufferGeometry();
  geo.setAttribute("position", new THREE.Float32BufferAttribute(bin.pos, 3));
  geo.setAttribute("uv", new THREE.Float32BufferAttribute(bin.uv, 2));
  geo.computeVertexNormals();
  return geo;
}

