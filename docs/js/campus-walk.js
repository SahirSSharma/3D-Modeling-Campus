// Campus Walk — the walk from Argo Hall, across Revelle Plaza, onto Ridge Walk.
//
// This is a look at the campus, not a game. There is no clock, nothing to dodge
// and no score; the only question it answers is "is this what it actually looks
// like walking there". Everything it draws is measured — see campus-world.js
// for which source is trusted for what, and why OSM is not trusted for height.
//
// Two ways to be in it. On the ground the walk is a rail: eye level at 1.65 m
// along the real route, which is the honest test — buildings are the right
// size or they are not. Off the ground there is a fly mode, because checking a
// campus against its sources also needs the surveyor's view: you spawn 110 m
// over Argo Hall, hold that altitude until you move, and can wind up to
// 250 m/s to cross the whole box in seconds. `F` drops you back onto the rail.
//
// Two viewpoints, because they check different things. Eye level is the honest
// test. The over-the-shoulder view is how the same world will be seen later,
// so it is worth knowing it holds up from there too.
import * as world from "./campus-world.js";
import { THREE } from "./campus-world.js";
import { buildGraph, routeThrough, makeMapTransform } from "./campus-route.js";

const CAMPUS_URL = new URL("../data/campus-3d.json", import.meta.url);
const LIDAR_URL = new URL("../data/campus-lidar.json", import.meta.url);
/* Optional: the official campus boundary, in local metres, generated by
   scripts/build-campus-satellite.mjs. The minimap draws it when present and
   simply goes without when not — the file is built by a separate pipeline and
   its absence must never take the walk down. */
const BOUNDARY_URL = new URL("../data/campus-boundary.json", import.meta.url);

const EYE_HEIGHT = 1.65;      // a person's eyes, not a drone's
const WALK_SPEED = 1.45;      // m/s, an ordinary pace
const FAST_SPEED = 4.2;       // holding shift on the rail, for getting back to a spot
const FLY_SPEED = 12;         // m/s cruising in fly mode without shift
const CHASE_BACK = 6.5;
const CHASE_HEIGHT = 3.4;
const SPACING = 2;            // metres between resampled route points

/* Exported so the tests can pin them: the spawn hangs exactly this far above
   the ground at Argo Hall, and no acceleration curve may pass this cap. */
export const SPAWN_ALTITUDE_M = 110;
export const MAX_SPEED_MPS = 250;

const state = {
  mode: "fly",         // fly | rail — boot() spawns airborne over Argo Hall
  s: 0,                // metres along the route (rail mode)
  px: 0, py: 0, pz: 0, // free position (fly mode; mirrored on the rail)
  vel: 0,              // commanded fly speed (the W/S wind-up), m/s
  speed: 0,            // actual speed this frame — |composed velocity|, m/s
  dir: 1,              // last commanded fly direction, so momentum can coast
  look: 0,             // absolute look heading this frame (for the minimap)
  auto: false,         // walking by itself (rail mode)
  view: "eye",         // eye | chase
  yaw: 0,              // rail: offset from route heading; fly: absolute heading
  pitch: -0.03,
  lastTime: 0,
};

let scene, camera, renderer, route, campus, lidar, boundary, heightAt, coverage, walker;
let landmarks = [];
let minimap = null;

/* --------------------------------------------------------------- geometry */

function sampleRoute(s) {
  const pts = route.points;
  const maxS = (pts.length - 1) * SPACING;
  const clamped = Math.max(0, Math.min(s, maxS));
  const i = Math.min(pts.length - 2, Math.floor(clamped / SPACING));
  const t = clamped / SPACING - i;
  const a = pts[i];
  const b = pts[i + 1];
  return {
    x: a.x + (b.x - a.x) * t,
    z: a.z + (b.z - a.z) * t,
    heading: Math.atan2(b.x - a.x, b.z - a.z),
  };
}

const routeLength = () => (route.points.length - 1) * SPACING;

/* ---------------------------------------------------------------- content */

/** Everything named within sight of the route, with where along it you pass. */
function findLandmarks() {
  const named = { ...campus.places };
  landmarks = [];
  for (const [name, place] of Object.entries(named)) {
    let bestS = -1;
    let bestD = Infinity;
    for (let i = 0; i < route.points.length; i += 2) {
      const p = route.points[i];
      const d = Math.hypot(p.x - place.x, p.z - place.z);
      if (d < bestD) { bestD = d; bestS = i * SPACING; }
    }
    if (bestD < 70) {
      landmarks.push({
        name, s: bestS, distance: Math.round(bestD),
        x: place.x, z: place.z,
        height: lidar.heights[name] ?? null,
      });
    }
  }
  landmarks.sort((a, b) => a.s - b.s);
}

/* ------------------------------------------------------------------ input */

function bindInput(canvas) {
  addEventListener("keydown", (e) => {
    if (e.key === "1") setView("eye");
    if (e.key === "2") setView("chase");
    if (e.key === " ") {
      if (state.mode === "rail") { state.auto = !state.auto; updateChrome(); }
      e.preventDefault();
    }
    if (e.key === "r" || e.key === "R") {
      state.mode = "rail"; state.s = 0; state.yaw = 0; state.vel = 0;
    }
    if (e.key === "f" || e.key === "F") toggleFly();
    if (e.key === "m" || e.key === "M") toggleMapSize();
    if (["ArrowUp", "ArrowDown", "ArrowLeft", "ArrowRight", "w", "s", "a", "d"].includes(e.key)) {
      e.preventDefault();
    }
  });

  const held = new Set();
  addEventListener("keydown", (e) => held.add(e.key.toLowerCase()));
  addEventListener("keyup", (e) => held.delete(e.key.toLowerCase()));
  state.held = held;

  /* Drag to look, exactly like Street View. Pointer events so a trackpad, a
     mouse and a finger all behave the same. */
  let dragging = false;
  let lastX = 0;
  let lastY = 0;
  canvas.addEventListener("pointerdown", (e) => {
    dragging = true; lastX = e.clientX; lastY = e.clientY;
    canvas.setPointerCapture(e.pointerId);
  });
  canvas.addEventListener("pointermove", (e) => {
    if (!dragging) return;
    state.yaw -= (e.clientX - lastX) * 0.005;
    state.pitch = Math.max(-0.9, Math.min(0.7, state.pitch - (e.clientY - lastY) * 0.004));
    lastX = e.clientX; lastY = e.clientY;
  });
  const stop = (e) => {
    dragging = false;
    if (canvas.hasPointerCapture?.(e.pointerId)) canvas.releasePointerCapture(e.pointerId);
  };
  canvas.addEventListener("pointerup", stop);
  canvas.addEventListener("pointercancel", stop);
}

function setView(view) {
  state.view = view;
  walker.visible = view === "chase";
  updateChrome();
}

/* Leave the rail into the air, or drop out of the air onto the nearest point
   of the route. Yaw is relative to the route heading on the rail and absolute
   in the air, so it is folded across on the way up and reset on the way down —
   the direction you are looking never jumps. */
function toggleFly() {
  if (state.mode === "fly") {
    let bestI = 0;
    let bestD = Infinity;
    for (let i = 0; i < route.points.length; i++) {
      const p = route.points[i];
      const d = Math.hypot(p.x - state.px, p.z - state.pz);
      if (d < bestD) { bestD = d; bestI = i; }
    }
    state.s = bestI * SPACING;
    state.mode = "rail";
    state.yaw = 0;
    state.vel = 0;
    state.auto = false;
  } else {
    const pos = sampleRoute(state.s);
    state.px = pos.x;
    state.pz = pos.z;
    state.py = heightAt(pos.x, pos.z) + EYE_HEIGHT;
    state.yaw = pos.heading + state.yaw; // keep looking the same way
    state.mode = "fly";
    state.vel = 0;
    state.auto = false;
  }
  updateChrome();
}

/** Minimap teleport: land standing at (x, z), eyes at ground + eye height. */
function teleportTo(x, z) {
  /* The minimap reaches the full boundary extent, but ground mesh (grid +
     apron) does not — a click past it would leave you standing over sky.
     Clamp into the covered rect: the click still goes to the nearest point
     that has ground under it. */
  if (coverage) {
    x = Math.max(coverage.x0, Math.min(coverage.x1, x));
    z = Math.max(coverage.z0, Math.min(coverage.z1, z));
  }
  /* Rail yaw is an offset from the route heading; fly yaw is absolute. Fold
     the heading in before switching modes — same as toggleFly — so the
     direction you are looking never jumps on a map click. */
  if (state.mode === "rail") state.yaw = sampleRoute(state.s).heading + state.yaw;
  state.mode = "fly"; // free position; press F to snap back onto the rail
  state.px = x;
  state.pz = z;
  state.py = heightAt(x, z) + EYE_HEIGHT;
  state.vel = 0;
  state.auto = false;
  updateChrome();
}

/* ------------------------------------------------------------------ update */

function update(dt) {
  if (state.mode === "fly") updateFly(dt);
  else updateRail(dt);
  updateHud();
}

function updateRail(dt) {
  const held = state.held;
  const fast = held.has("shift");
  const speed = (fast ? FAST_SPEED : WALK_SPEED) * dt;

  let moved = 0;
  if (held.has("w") || held.has("arrowup")) { moved += speed; state.auto = false; }
  if (held.has("s") || held.has("arrowdown")) { moved -= speed; state.auto = false; }
  if (held.has("a") || held.has("arrowleft")) state.yaw += dt * 1.1;
  if (held.has("d") || held.has("arrowright")) state.yaw -= dt * 1.1;
  if (state.auto) moved += speed;

  if (moved) {
    state.s = Math.max(0, Math.min(routeLength(), state.s + moved));
    if (state.s >= routeLength()) state.auto = false;
  }
  state.speed = dt > 0 ? Math.abs(moved) / dt : 0;

  const pos = sampleRoute(state.s);
  const ground = heightAt(pos.x, pos.z);

  /* Mirror onto the free position so the minimap has one source of truth. */
  state.px = pos.x;
  state.pz = pos.z;
  state.py = ground + EYE_HEIGHT;

  walker.position.set(pos.x, ground, pos.z);
  walker.rotation.y = pos.heading;
  /* A walk cycle, so the figure is not skating in the chase view. */
  const swing = Math.sin(state.s * 1.9) * 0.35;
  walker.userData.legs[0].rotation.x = swing;
  walker.userData.legs[1].rotation.x = -swing;

  const look = pos.heading + state.yaw;
  state.look = look;
  if (state.view === "eye") {
    camera.position.set(pos.x, ground + EYE_HEIGHT, pos.z);
  } else {
    const target = new THREE.Vector3(
      pos.x - Math.sin(look) * CHASE_BACK,
      ground + CHASE_HEIGHT,
      pos.z - Math.cos(look) * CHASE_BACK
    );
    target.y = Math.max(target.y, heightAt(target.x, target.z) + 1.6);
    camera.position.lerp(target, Math.min(1, dt * 6));
  }

  aimCamera(look);
}

/* Fly mode. No gravity — you hold whatever altitude you have, which is what
   lets the spawn hang 110 m over Argo Hall until the first key is pressed.
   W/S move along the view direction (pitch included, so looking down and
   pressing W descends); Q/E move straight up and down; shift winds the speed
   up along a curve that steepens as it goes and stops dead at MAX_SPEED_MPS.
   Releasing the keys coasts to a stop rather than parking mid-air instantly —
   at 250 m/s an instant stop reads as a crash. */
function updateFly(dt) {
  const held = state.held;
  if (held.has("a") || held.has("arrowleft")) state.yaw += dt * 1.1;
  if (held.has("d") || held.has("arrowright")) state.yaw -= dt * 1.1;

  let dir = 0;
  if (held.has("w") || held.has("arrowup")) dir += 1;
  if (held.has("s") || held.has("arrowdown")) dir -= 1;
  if (dir) state.dir = dir;

  const target = dir ? (held.has("shift") ? MAX_SPEED_MPS : FLY_SPEED) : 0;
  if (state.vel < target) {
    state.vel = Math.min(target, state.vel + (20 + state.vel * 1.5) * dt);
  } else {
    state.vel = Math.max(target, state.vel - Math.max(260, state.vel * 2.5) * dt);
  }

  const look = state.yaw;
  state.look = look;
  /* Compose the frame's velocity as one vector and clamp its MAGNITUDE, so
     the cap is the cap: W plus Q at full wind-up is still 250 m/s, not
     √(250² + climb²). */
  let vx = 0, vy = 0, vz = 0;
  if (state.vel > 0.01) {
    const cp = Math.cos(state.pitch);
    vx = Math.sin(look) * cp * state.vel * state.dir;
    vz = Math.cos(look) * cp * state.vel * state.dir;
    vy = Math.sin(state.pitch) * state.vel * state.dir;
  }
  const vert = Math.max(6, state.vel * 0.4);
  if (held.has("q")) vy += vert;
  if (held.has("e")) vy -= vert;
  const mag = Math.hypot(vx, vy, vz);
  if (mag > MAX_SPEED_MPS) {
    const f = MAX_SPEED_MPS / mag;
    vx *= f; vy *= f; vz *= f;
  }
  /* What the HUD shows: the speed you are actually moving at. state.vel is
     only the W/S wind-up, which reads 0 during a pure Q/E climb. */
  state.speed = Math.min(mag, MAX_SPEED_MPS);
  state.px += vx * dt;
  state.pz += vz * dt;
  state.py += vy * dt;

  /* Stay over the data. Beyond ±5 km there is nothing to see and float error
     starts to matter; below ground there is never anything to see. */
  state.px = Math.max(-5000, Math.min(5000, state.px));
  state.pz = Math.max(-5000, Math.min(5000, state.pz));
  const ground = heightAt(state.px, state.pz);
  state.py = Math.max(ground + EYE_HEIGHT, Math.min(3000, state.py));

  walker.position.set(state.px, state.py - EYE_HEIGHT, state.pz);
  walker.rotation.y = look;

  if (state.view === "eye") {
    camera.position.set(state.px, state.py, state.pz);
  } else {
    const target = new THREE.Vector3(
      state.px - Math.sin(look) * CHASE_BACK,
      state.py - EYE_HEIGHT + CHASE_HEIGHT,
      state.pz - Math.cos(look) * CHASE_BACK
    );
    target.y = Math.max(target.y, heightAt(target.x, target.z) + 1.6);
    camera.position.lerp(target, Math.min(1, dt * 6));
  }

  aimCamera(look);
}

function aimCamera(look) {
  const aim = state.view === "eye" ? 14 : 18;
  camera.lookAt(
    camera.position.x + Math.sin(look) * aim,
    camera.position.y + Math.sin(state.pitch) * aim,
    camera.position.z + Math.cos(look) * aim
  );
}

/* ----------------------------------------------------------------- minimap */

/* The minimap is built entirely from here — a canvas dropped onto the page,
   no markup changes. Static content (footprints, paths, the walked route, the
   campus boundary) renders once to an offscreen canvas; per frame it is one
   drawImage plus a dot. Clicking or tapping anywhere on it teleports you
   there; `M` grows it into an overview of the whole data box. */
function createMinimap() {
  const pad = 60;
  let minX = Infinity, maxX = -Infinity, minZ = Infinity, maxZ = -Infinity;
  const eat = (x, z) => {
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (z < minZ) minZ = z;
    if (z > maxZ) maxZ = z;
  };
  for (const p of campus.paths) for (const [x, z] of p.p) eat(x, z);
  for (const b of campus.buildings) for (const [x, z] of b.p) eat(x, z);
  if (boundary) for (const [x, z] of boundary.points) eat(x, z);
  const bounds = {
    minX: minX - pad, maxX: maxX + pad,
    minZ: minZ - pad, maxZ: maxZ + pad,
  };

  /* Internal resolution: longest side 1100 px, so the expanded view stays
     sharp; CSS decides how big it appears. */
  const worldW = bounds.maxX - bounds.minX;
  const worldH = bounds.maxZ - bounds.minZ;
  const k = 1100 / Math.max(worldW, worldH);
  const W = Math.round(worldW * k);
  const H = Math.round(worldH * k);
  const tf = makeMapTransform(bounds, W, H);

  const bg = document.createElement("canvas");
  bg.width = W; bg.height = H;
  const b = bg.getContext("2d");

  b.fillStyle = "rgba(243, 240, 233, 0.94)";
  b.fillRect(0, 0, W, H);

  const ring = (ctx, pts) => {
    ctx.beginPath();
    pts.forEach(([x, z], i) => {
      const [mx, my] = tf.toMap(x, z);
      i ? ctx.lineTo(mx, my) : ctx.moveTo(mx, my);
    });
    ctx.closePath();
  };

  for (const s of campus.surfaces || []) {
    if (!s.p || s.p.length < 3) continue;
    ring(b, s.p);
    b.fillStyle = s.kind === "water" ? "#a6c6d8" : s.kind === "plaza" ? "#e2dccd" : "#c9d6ae";
    b.fill();
  }

  b.strokeStyle = "#d6d0c2";
  b.lineWidth = 1;
  for (const p of campus.paths) {
    b.beginPath();
    p.p.forEach(([x, z], i) => {
      const [mx, my] = tf.toMap(x, z);
      i ? b.lineTo(mx, my) : b.moveTo(mx, my);
    });
    b.stroke();
  }

  b.fillStyle = "#b3ab9b";
  for (const bd of campus.buildings) {
    ring(b, bd.p);
    b.fill();
  }

  /* The walked route, so the rail is findable from the air. */
  b.strokeStyle = "#2563c4";
  b.lineWidth = 2.5;
  b.beginPath();
  route.points.forEach((p, i) => {
    const [mx, my] = tf.toMap(p.x, p.z);
    i ? b.lineTo(mx, my) : b.moveTo(mx, my);
  });
  b.stroke();

  /* The campus boundary — dashed dark navy, the same line the world draws on
     the ground, so in-world and map agree about where campus ends. */
  if (boundary?.points?.length >= 3) {
    b.save();
    b.setLineDash([12, 8]);
    b.strokeStyle = "#16295e";
    b.lineWidth = 3;
    ring(b, boundary.points);
    b.stroke();
    b.restore();
  }

  const el = document.createElement("canvas");
  el.id = "walk-minimap";
  el.width = W; el.height = H;
  el.title = "Click to teleport — M to enlarge";
  Object.assign(el.style, {
    position: "fixed",
    right: "12px",
    bottom: "12px",
    width: "190px",
    height: "auto",
    zIndex: "40",
    borderRadius: "8px",
    border: "1px solid rgba(20, 30, 50, 0.45)",
    boxShadow: "0 4px 18px rgba(0, 0, 0, 0.35)",
    cursor: "crosshair",
    touchAction: "none",
  });
  document.body.appendChild(el);

  /* Click and touch both arrive as pointerdown. Coordinates are mapped
     through the element's on-screen rect, so the same handler is correct at
     every display size. */
  el.addEventListener("pointerdown", (e) => {
    e.preventDefault();
    e.stopPropagation();
    const rect = el.getBoundingClientRect();
    const mx = ((e.clientX - rect.left) / rect.width) * el.width;
    const my = ((e.clientY - rect.top) / rect.height) * el.height;
    const [x, z] = tf.toWorld(mx, my);
    teleportTo(x, z);
  });

  minimap = { el, ctx: el.getContext("2d"), bg, tf, expanded: false };
  applyMapSize();
}

function applyMapSize() {
  if (!minimap) return;
  const ar = minimap.el.width / minimap.el.height;
  if (minimap.expanded) {
    const w = Math.min(innerWidth * 0.72, innerHeight * 0.78 * ar);
    minimap.el.style.width = `${Math.round(w)}px`;
  } else {
    minimap.el.style.width = "190px";
  }
}

function toggleMapSize() {
  if (!minimap) return;
  minimap.expanded = !minimap.expanded;
  applyMapSize();
}

function drawMinimap() {
  if (!minimap) return;
  const { ctx, bg, tf, el } = minimap;
  ctx.clearRect(0, 0, el.width, el.height);
  ctx.drawImage(bg, 0, 0);

  const [mx, my] = tf.toMap(state.px, state.pz);
  /* Heading tick: world (sin look, cos look) maps straight to (x, +y) because
     map y is +z. */
  ctx.strokeStyle = "#d62828";
  ctx.lineWidth = 3;
  ctx.beginPath();
  ctx.moveTo(mx, my);
  ctx.lineTo(mx + Math.sin(state.look) * 16, my + Math.cos(state.look) * 16);
  ctx.stroke();

  ctx.beginPath();
  ctx.arc(mx, my, 6, 0, Math.PI * 2);
  ctx.fillStyle = "#d62828";
  ctx.fill();
  ctx.lineWidth = 2;
  ctx.strokeStyle = "#ffffff";
  ctx.stroke();
}

/* -------------------------------------------------------------------- HUD */

let lastCalled = null;
function updateHud() {
  /* routeLength(), not route.metres. The two differ — route.metres includes the
     walk from a building's centroid out to the nearest path at each end, which
     is real distance a person covers but is not part of the line being walked.
     Showing one against the other put "11 m of 371 m" beside a progress bar
     that was measuring against 346, so the numbers disagreed on screen. */
  const distanceEl = document.getElementById("walk-distance");
  if (state.mode === "fly") {
    const up = Math.max(0, state.py - heightAt(state.px, state.pz));
    /* state.speed, not state.vel — vel is only the W/S wind-up and shows 0
       during a pure Q/E climb, which reads as a broken speedometer. */
    distanceEl.textContent = `${Math.round(state.speed)} m/s · ${Math.round(up)} m up`;
  } else {
    const metres = Math.round(state.s);
    distanceEl.textContent = `${metres} m of ${Math.round(routeLength())} m`;
  }
  /* The progress bar measures the walk; in the air it would hold a stale
     rail percentage, so it empties until you are back on the route. */
  document.getElementById("walk-progress").style.width =
    state.mode === "fly" ? "0%" : `${Math.min(100, (state.s / routeLength()) * 100)}%`;

  /* What you are passing right now, and how tall it measured. Naming the
     height on screen is deliberate: it is the claim being made, so it should
     be checkable against the building in front of you. On the rail nearness is
     measured along the route; in the air it is plain distance. */
  let current = null;
  if (state.mode === "fly") {
    for (const l of landmarks) {
      const d = Math.hypot(l.x - state.px, l.z - state.pz);
      if (d < 80 && (!current || d < current.d)) current = { ...l, d };
    }
    current = current && landmarks.find((l) => l.name === current.name);
  } else {
    for (const l of landmarks) {
      if (state.s >= l.s - 26 && state.s <= l.s + 22) {
        if (!current || Math.abs(l.s - state.s) < Math.abs(current.s - state.s)) current = l;
      }
    }
  }
  const el = document.getElementById("walk-here");
  if (current !== lastCalled) {
    lastCalled = current;
    if (current) {
      el.innerHTML = current.height
        ? `${current.name} <span class="walk-h">${current.height} m</span>`
        : current.name;
      el.classList.add("show");
    } else {
      el.classList.remove("show");
    }
  }
}

function updateChrome() {
  const view = document.getElementById("walk-view");
  if (view) {
    view.textContent =
      state.mode === "fly" ? "Flying" : state.view === "eye" ? "Eye level" : "Over the shoulder";
  }
  const play = document.getElementById("walk-play");
  if (play) play.textContent = state.auto ? "Pause" : "Walk";
}

/* ------------------------------------------------------------------- boot */

function frame(now) {
  requestAnimationFrame(frame);
  const dt = Math.min(0.05, (now - state.lastTime) / 1000 || 0);
  state.lastTime = now;
  update(dt);
  drawMinimap();
  renderer.render(scene, camera);
}

function resize() {
  const canvas = renderer.domElement;
  const w = canvas.clientWidth || 1;
  const h = canvas.clientHeight || 1;
  renderer.setSize(w, h, false);
  camera.aspect = w / h;
  camera.updateProjectionMatrix();
  applyMapSize();
}

export async function boot() {
  [campus, lidar] = await Promise.all([
    fetch(CAMPUS_URL).then((r) => r.json()),
    fetch(LIDAR_URL).then((r) => r.json()),
  ]);

  /* The boundary is optional by design; see BOUNDARY_URL above. */
  boundary = await fetch(BOUNDARY_URL)
    .then((r) => (r.ok ? r.json() : null))
    .catch(() => null);
  if (!Array.isArray(boundary?.points) || boundary.points.length < 3) boundary = null;

  const graph = buildGraph(campus);
  /* The destination is a real point on Ridge Walk rather than the name's
     centroid: "Ridge Walk" is twenty separate ways spanning 1.7 km, so its
     centroid is a spot in the middle of campus that means nothing. This picks
     the Ridge Walk vertex nearest to 300 m north of the plaza. */
  const plaza = campus.places["Revelle Plaza"];
  const ridge = campus.paths.filter((p) => p.n === "Ridge Walk").flatMap((p) => p.p);
  const target = { x: plaza.x, z: plaza.z - 300 };
  let end = null;
  let bestD = Infinity;
  for (const [x, z] of ridge) {
    const d = Math.hypot(x - target.x, z - target.z);
    if (d < bestD) { bestD = d; end = { x, z, name: "Ridge Walk" }; }
  }
  route = routeThrough(campus, graph, ["Argo Hall", "Revelle Plaza", end]);

  const canvas = document.getElementById("walk-canvas");
  renderer = new THREE.WebGLRenderer({ canvas, antialias: true });
  renderer.setPixelRatio(Math.min(2, devicePixelRatio));

  scene = world.createScene();
  camera = new THREE.PerspectiveCamera(68, 1, 0.4, 900);

  const terrain = world.createTerrain(scene, lidar);
  heightAt = terrain.heightAt;
  coverage = terrain.coverage; // where ground mesh exists — teleports clamp into it
  const built = world.createBuildings(scene, campus, lidar, heightAt);
  const surfaces = world.createSurfaces(scene, campus, heightAt);
  const paths = world.createPaths(scene, campus, heightAt);
  const trees = world.createTrees(scene, lidar, heightAt);

  walker = world.createWalker();
  scene.add(walker);
  walker.visible = false;

  /* SPAWN: hanging SPAWN_ALTITUDE_M over Argo Hall, holding altitude — fly
     mode has no gravity, so nothing moves until a key does. Facing north
     (-z), pitched down enough that the campus is in frame rather than the
     horizon. */
  const argo = campus.places["Argo Hall"];
  state.mode = "fly";
  state.px = argo.x;
  state.pz = argo.z;
  state.py = heightAt(argo.x, argo.z) + SPAWN_ALTITUDE_M;
  state.yaw = Math.PI;
  state.pitch = -0.35;
  state.vel = 0;
  state.auto = false;

  findLandmarks();
  bindInput(canvas);
  createMinimap();
  resize();
  addEventListener("resize", resize);
  document.getElementById("walk-play")?.addEventListener("click", () => {
    /* From the air, "Walk" means it: land on the rail, then start walking. */
    if (state.mode === "fly") toggleFly();
    state.auto = !state.auto; updateChrome();
  });
  document.getElementById("walk-toggle")?.addEventListener("click", () => {
    setView(state.view === "eye" ? "chase" : "eye");
  });
  updateChrome();

  state.lastTime = performance.now();
  frame(performance.now());

  /* The layers are handed back so a development harness can switch them off
     one at a time. That is not a nicety — nearly every rendering bug found so
     far was invisible until something was hidden. The plaza drawn on the wrong
     side of the origin, the walls wearing the roof's colour, canopies
     swallowing the camera: each of those is obvious the moment you can turn
     off the thing in front of it, and nearly impossible to spot otherwise. */
  return {
    metres: route.metres,
    buildings: built.total,
    measured: built.measured,
    trees: trees.count,
    landmarks: landmarks.length,
    scene,
    camera,
    renderer,
    layers: {
      terrain: terrain.mesh,
      buildings: built.group,
      surfaces,
      paths,
      trees: trees.group,
    },
    /* The harness can also move the player — the same call a minimap click
       makes, so a teleport is scriptable end to end. */
    teleport: teleportTo,
    minimap: () => minimap,
    /* Live read-out for the harness: where you are, what you are passing, and
       what it measured. */
    status: () => {
      const near = landmarks.reduce(
        (best, l) => (Math.abs(l.s - state.s) < Math.abs((best?.s ?? 1e9) - state.s) ? l : best),
        null
      );
      return {
        mode: state.mode,
        s: state.s,
        total: routeLength(),
        view: state.view,
        auto: state.auto,
        x: state.px, y: state.py, z: state.pz,
        speed: state.speed,
        ground: heightAt(state.px, state.pz),
        heading: (state.look * 180) / Math.PI,
        near,
      };
    },
  };
}
